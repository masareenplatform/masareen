from abc import ABC, abstractmethod
from typing import List, Optional, Tuple
from .evidence import Evidence

class EvidenceRepository(ABC):
    @abstractmethod
    async def get_by_id(self, evidence_id: str) -> Optional[Evidence]: ...
    @abstractmethod
    async def save(self, evidence: Evidence) -> Evidence: ...
    @abstractmethod
    async def list_by_task(self, task_id: str) -> List[Evidence]: ...
    @abstractmethod
    async def list_by_submitter(self, user_id: str, limit: int, offset: int) -> Tuple[List[Evidence], int]: ...
    @abstractmethod
    async def find_by_checksum(self, checksum: str) -> Optional[Evidence]: ...
