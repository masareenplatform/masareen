class MasarenLocalizationsDelegate
    extends LocalizationsDelegate<MasarenLocalizations> {
  const MasarenLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['en', 'ar'].contains(locale.languageCode);

  @override
  Future<MasarenLocalizations> load(Locale locale) {
    final appLocale = locale.languageCode == 'ar' ? AppLocale.ar : AppLocale.en;
    return Future.value(MasarenLocalizations(appLocale));
  }

  @override
  bool shouldReload(
          covariant LocalizationsDelegate<MasarenLocalizations> oldDelegate) =>
      false;
}
