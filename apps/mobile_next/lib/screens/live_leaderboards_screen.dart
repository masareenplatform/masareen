import 'package:flutter/material.dart';
import 'package:intl/intl.dart';
import 'package:masaren/api_client.dart';
import 'package:masaren/models.dart';
import 'package:masaren/screens/create_leaderboard_screen.dart';
import 'package:masaren/theme.dart';
import 'package:masaren/widgets.dart';

class LiveLeaderboardsScreen extends StatefulWidget {
  final User user;
  const LiveLeaderboardsScreen({super.key, required this.user});

  @override
  State<LiveLeaderboardsScreen> createState() => _LiveLeaderboardsScreenState();
}

class _LiveLeaderboardsScreenState extends State<LiveLeaderboardsScreen> {
  static const _scopes = [
    'institutions',
    'journalists',
    'research',
    'programs',
    'events',
  ];
  String _scope = 'institutions';
  String _period = 'month';
  List<Map<String, dynamic>> _rankings = [];
  bool _loading = true;
  String? _generatedAt;

  @override
  void initState() {
    super.initState();
    _load();
  }

  Future<void> _load() async {
    setState(() => _loading = true);
    try {
      final data = await AuthApi.liveLeaderboard(
        scope: _scope,
        period: _period,
        limit: 30,
      );
      if (!mounted) return;
      setState(() {
        _rankings = (data['rankings'] as List? ?? const [])
            .whereType<Map>()
            .map((e) => Map<String, dynamic>.from(e))
            .toList();
        _generatedAt = data['generated_at']?.toString();
      });
    } catch (_) {
      if (mounted) setState(() => _rankings = []);
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    return Scaffold(
      appBar: AppBar(
        title: const Text('Live leaderboards'),
        actions: [
          IconButton(
            onPressed: () => Navigator.of(context).push(
              MaterialPageRoute(
                builder: (_) => CreateLeaderboardScreen(user: widget.user),
              ),
            ),
            tooltip: 'Create a challenge leaderboard',
            icon: const Icon(Icons.add_chart),
          ),
          IconButton(onPressed: _load, icon: const Icon(Icons.refresh)),
        ],
      ),
      body: RefreshIndicator(
        onRefresh: _load,
        child: ListView(
          padding: const EdgeInsets.fromLTRB(16, 10, 16, 30),
          children: [
            Container(
              padding: const EdgeInsets.all(16),
              decoration: BoxDecoration(
                gradient: const LinearGradient(
                  colors: [Color(0xFF0E6B5C), Color(0xFF0A3F36)],
                ),
                borderRadius: BorderRadius.circular(20),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Text(
                    'Generated by the platform',
                    style: TextStyle(
                      color: AppColors.gold,
                      fontSize: 10,
                      letterSpacing: 1.3,
                      fontWeight: FontWeight.w900,
                    ),
                  ),
                  const SizedBox(height: 5),
                  const Text(
                    'Live impact rankings',
                    style: TextStyle(
                      color: Colors.white,
                      fontSize: 21,
                      fontWeight: FontWeight.w900,
                    ),
                  ),
                  const SizedBox(height: 4),
                  Text(
                    _generatedAt == null
                        ? 'Event-driven, data-driven and updated automatically.'
                        : 'Updated ${DateFormat.yMMMd().add_jm().format(DateTime.tryParse(_generatedAt!)?.toLocal() ?? DateTime.now())}',
                    style: TextStyle(
                      color: Colors.white.withValues(alpha: .7),
                      fontSize: 11.5,
                    ),
                  ),
                ],
              ),
            ),
            const SizedBox(height: 12),
            SingleChildScrollView(
              scrollDirection: Axis.horizontal,
              child: Row(
                children: [
                  for (final scope in _scopes)
                    Padding(
                      padding: const EdgeInsetsDirectional.only(end: 6),
                      child: ChoiceChip(
                        label: Text(
                          scope[0].toUpperCase() + scope.substring(1),
                        ),
                        selected: _scope == scope,
                        onSelected: (_) {
                          setState(() => _scope = scope);
                          _load();
                        },
                      ),
                    ),
                ],
              ),
            ),
            const SizedBox(height: 6),
            Row(
              children: [
                for (final period in ['week', 'month', 'all'])
                  Padding(
                    padding: const EdgeInsetsDirectional.only(end: 6),
                    child: ChoiceChip(
                      label: Text(
                        period == 'all'
                            ? 'All time'
                            : period == 'week'
                                ? 'This week'
                                : 'This month',
                      ),
                      selected: _period == period,
                      onSelected: (_) {
                        setState(() => _period = period);
                        _load();
                      },
                    ),
                  ),
              ],
            ),
            const SizedBox(height: 12),
            if (_loading)
              const Center(
                child: Padding(
                  padding: EdgeInsets.all(40),
                  child: CircularProgressIndicator(),
                ),
              )
            else if (_rankings.isEmpty)
              Padding(
                padding: const EdgeInsets.all(40),
                child: Center(
                  child: Text(
                    'No rankings yet. Activity will populate this live board.',
                    textAlign: TextAlign.center,
                    style: TextStyle(color: cs.onSurfaceVariant),
                  ),
                ),
              )
            else
              ..._rankings.map((r) {
                final rank = (r['rank'] as num?)?.toInt() ?? 0;
                return Card(
                  child: ListTile(
                    contentPadding: const EdgeInsets.symmetric(
                      horizontal: 14,
                      vertical: 6,
                    ),
                    leading: SizedBox(
                      width: 42,
                      child: Row(
                        children: [
                          SizedBox(
                            width: 22,
                            child: Text(
                              '#$rank',
                              style: TextStyle(
                                fontWeight: FontWeight.w900,
                                color: rank <= 3
                                    ? AppColors.accent
                                    : cs.onSurfaceVariant,
                              ),
                            ),
                          ),
                          AppAvatar(
                            name: r['name']?.toString() ?? 'Member',
                            url: r['avatar_url']?.toString(),
                            size: 34,
                          ),
                        ],
                      ),
                    ),
                    title: Text(
                      r['name']?.toString() ?? '',
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                      style: const TextStyle(fontWeight: FontWeight.w800),
                    ),
                    subtitle: Text(
                      r['subtitle']?.toString() ?? '',
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                      style: TextStyle(
                        fontSize: 10.5,
                        color: cs.onSurfaceVariant,
                      ),
                    ),
                    trailing: Column(
                      mainAxisAlignment: MainAxisAlignment.center,
                      crossAxisAlignment: CrossAxisAlignment.end,
                      children: [
                        Text(
                          (r['score'] as num?)?.toStringAsFixed(1) ?? '0',
                          style: TextStyle(
                            fontSize: 15,
                            fontWeight: FontWeight.w900,
                            color: cs.primary,
                          ),
                        ),
                        Text(
                          'impact',
                          style: TextStyle(
                            fontSize: 9,
                            color: cs.onSurfaceVariant,
                          ),
                        ),
                      ],
                    ),
                  ),
                );
              }),
          ],
        ),
      ),
    );
  }
}
